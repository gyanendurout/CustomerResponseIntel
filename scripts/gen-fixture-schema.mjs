// from the live PostgREST OpenAPI document) for PGlite tests. Contains no data.
import { readFileSync, writeFileSync } from 'node:fs';
const defs = JSON.parse(readFileSync(new URL('./out/openapi.json', import.meta.url))).definitions;
const TABLES = ['brands', 'mention_facts', 'ig_comments', 'yt_comments', 'reddit_mentions', 'reddit_comments', 'tiktok_comments',
  'competitor_switch_events', 'topic_lifecycle', 'brand_replies', 'paddle_reviews', 'tiktok_videos', 'x_posts',
  'influencer_x_posts', 'yt_videos', 'ig_posts',
  'ig_accounts', 'ig_profiles_weekly', 'yt_channels', 'yt_channel_weekly', 'yt_video_analysis', 'x_accounts',
  'x_profiles_weekly', 'tiktok_accounts', 'tiktok_profiles_weekly', 'products_catalog', 'influencers'];
let sql = '-- GENERATED by scripts/gen-fixture-schema.mjs from the live schema. Do not edit by hand.\n';
for (const t of TABLES) {
  const d = defs[t]; const req = new Set(d.required || []);
  const cols = Object.entries(d.properties).map(([c, p]) => {
    let def = '';
    if (p.default !== undefined && !String(p.default).includes('(')) def = ` default ${typeof p.default === 'string' ? `'${p.default}'` : p.default}`;
    if (String(p.default) === 'gen_random_uuid()') def = ' default gen_random_uuid()';
    if (String(p.default) === 'now()') def = ' default now()';
    return `  "${c}" ${p.format}${req.has(c) ? ' not null' : ''}${def}${(p.description || '').includes('<pk/>') ? ' primary key' : ''}`;
  });
  sql += `create table public.${t} (\n${cols.join(',\n')}\n);\n`;
}
writeFileSync(new URL('../tests/fixtures/public-schema.sql', import.meta.url), sql);
console.log('ok', TABLES.length, 'tables');
